import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const directory = path.join(root, 'templates/html-home')
const files = {}
function walk(current) {
  for (const item of fs.readdirSync(current, { withFileTypes: true })) {
    if (item.name.startsWith('.') || ['node_modules', 'dist', 'output'].includes(item.name))
      continue
    const filename = path.join(current, item.name)
    if (item.isDirectory()) walk(filename)
    else if (item.isFile())
      files[path.relative(directory, filename).split(path.sep).join('/')] = fs
        .readFileSync(filename, 'utf8')
        .replaceAll('\r\n', '\n')
  }
}
walk(directory)
for (const required of ['index.html', 'app.js', 'style.css', 'lumi-sdk.js', 'lumi.home.json']) {
  if (!files[required]) throw new Error(`Official HTML template is missing ${required}`)
}
const content = `// SPDX-License-Identifier: MPL-2.0\n// Generated by scripts/bundle-home-template.mjs.\n\nexport const HOME_TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)}\n`
const output = path.join(root, 'packages/core/src/workbench/template-files.ts')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replaceAll('\r\n', '\n') !== content) {
    console.error('Embedded home template is stale; run pnpm sync:home')
    process.exitCode = 1
  }
} else fs.writeFileSync(output, content)
