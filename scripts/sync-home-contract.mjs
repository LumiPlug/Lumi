import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const release = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version
const normalize = (value) => value.replaceAll('\r\n', '\n')
const contract = { lumiVersion: release, sdkVersion: release, bridgeVersion: 1, formatVersion: 2 }
const manifest = {
  formatVersion: 2,
  template: 'lumi-html-home',
  lumiVersion: release,
  sdkVersion: release,
  bridgeVersion: 1,
  projectId: '00000000-0000-4000-8000-000000000001',
  name: '我的主页',
  entry: 'index.html',
}
const banner = '// SPDX-License-Identifier: MPL-2.0\n// Generated by scripts/sync-home-contract.mjs; do not edit by hand.\n\n'
const output = new Map([
  ['packages/shared/src/home-contract.ts', `${banner}export const HOME_CONTRACT = ${JSON.stringify(contract, null, 2)} as const\n`],
  ['packages/home-sdk/src/version.ts', `${banner}export const SDK_CONTRACT = ${JSON.stringify({ lumiVersion: release, sdkVersion: release, bridgeVersion: 1 }, null, 2)} as const\n`],
  ['templates/html-home/lumi.home.json', `${JSON.stringify(manifest, null, 2)}\n`],
  ['templates/html-home/knowledge/versions.json', `${JSON.stringify(contract, null, 2)}\n`],
  ['templates/html-home/theme.css', `${fs.readFileSync(path.join(root, 'src/theme/obsidian-solar-amber.css'), 'utf8')}\n${fs.readFileSync(path.join(root, 'src/theme/palette.css'), 'utf8')}`],
])
const sdk = await build({
  entryPoints: [path.join(root, 'packages/home-sdk/src/browser.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'safari15.4',
  minify: true,
  legalComments: 'none',
  logLevel: 'silent',
})
output.set('templates/html-home/lumi-sdk.js', `// SPDX-License-Identifier: MPL-2.0\n${sdk.outputFiles[0].text}`)
let stale = false
for (const [relative, raw] of output) {
  const target = path.join(root, relative)
  const content = normalize(raw)
  if (check) {
    if (!fs.existsSync(target) || normalize(fs.readFileSync(target, 'utf8')) !== content) {
      console.error(`Home contract is stale: ${relative}`)
      stale = true
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
  }
}
const versions = [
  JSON.parse(fs.readFileSync(path.join(root, 'src-tauri/tauri.conf.json'), 'utf8')).version,
  ...['core', 'shared', 'mcp-stdio-proxy', 'home-sdk'].map((name) =>
    JSON.parse(fs.readFileSync(path.join(root, 'packages', name, 'package.json'), 'utf8')).version,
  ),
]
const cargo = fs.readFileSync(path.join(root, 'src-tauri/Cargo.toml'), 'utf8').match(/^version = "([^"]+)"/m)?.[1]
if ([...versions, cargo].some((version) => version !== release)) {
  console.error('Lumi release versions differ')
  stale = true
}
if (stale) process.exitCode = 1
else console.log(`${check ? 'Checked' : 'Synchronized'} Lumi HTML home contract ${release}`)
